class OV5640:
    def write(self, reg, data):
        write_reg(reg, data)

    def read(self, reg):
        return read_reg(reg)

    def write16(self, reg, data):
        self.write(reg, (data >> 8))
        self.write(reg + 1, (data & 0xFF))

    def chip_id(self):
        return ((self.read(0x300A) << 8) | self.read(0x300B))

    def configure(self):
        default = iter(default_regs)
        for reg, data in zip(default, default):
            if (reg == DELAY):
                time.sleep(data)
            else:
                self.write(reg, data)
        
        qvga = iter(qvga_table)
        for reg, data in zip(qvga, qvga):
            self.write(reg, data)

        pll = iter(pll_table)
        for reg, data in zip(pll, pll):
            self.write(reg, data)

        yuv = iter(yuv_table)
        for reg, data in zip(yuv, yuv):
            self.write(reg, data)

        print(f"chip ID 0x{self.chip_id()}")
        print(f"clock ctrl 0x{self.read(0x4740)}")
        print(f"ctrl reg 0x{self.read(0x4300)}")

